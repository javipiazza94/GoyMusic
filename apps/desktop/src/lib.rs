//! GoyMusic desktop app: adapts `goymusic-services` to Tauri commands and events. The only
//! crate in the workspace that knows about Tauri (spec §3).

pub mod art_protocol;
mod commands;
mod forward;
mod logging;

use std::path::Path;
use std::sync::Arc;

use goymusic_audio::cpal_sink::CpalSink;
use goymusic_audio::sink::AudioSink;
use goymusic_services::{Services, ServicesConfig};
use specta_typescript::Typescript;
use tauri::RunEvent;
use tauri_specta::{collect_commands, collect_events, Builder};

pub use forward::CoreEvent;

const BINDINGS_HEADER: &str = "// Generated by tauri-specta. Do not edit.\n";

pub fn specta_builder() -> Builder<tauri::Wry> {
    use commands::*;
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            folders,
            add_folder,
            remove_folder,
            rescan,
            albums,
            album,
            artists,
            artist,
            tracks,
            track,
            recent_albums,
            search,
            playlists,
            playlist_folders,
            playlist,
            create_playlist,
            rename_playlist,
            delete_playlist,
            add_to_playlist,
            remove_from_playlist,
            move_playlist_item,
            create_playlist_folder,
            move_playlist_to_folder,
            like,
            unlike,
            liked_tracks,
            liked_ids,
            import_m3u,
            export_m3u,
            play,
            pause,
            resume,
            next,
            previous,
            seek,
            set_shuffle,
            set_repeat,
            set_volume,
            set_replaygain,
            queue_add,
            queue_remove,
            queue_move,
            player_view,
            settings,
        ])
        .events(collect_events![CoreEvent])
        // ids are SQLite rowids and times are milliseconds: always far below 2^53
        .dangerously_cast_bigints_to_number()
}

pub fn export_bindings(path: &Path) -> Result<(), specta_typescript::Error> {
    specta_builder().export(Typescript::default().header(BINDINGS_HEADER), path)
}

pub fn run() {
    let log_guard = logging::init();
    #[cfg(debug_assertions)]
    if let Err(e) = export_bindings(Path::new(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../ui/src/bindings.ts"
    ))) {
        tracing::warn!(error = %e, "could not export TypeScript bindings");
    }
    let sink = Box::new(|| CpalSink::open_default().map(|s| Box::new(s) as Box<dyn AudioSink>));
    let services = Arc::new(Services::start(ServicesConfig::default_paths(), sink).expect("start GoyMusic services"));
    let builder = specta_builder();
    let art_services = services.clone();
    let forward_services = services.clone();
    let app = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(builder.invoke_handler())
        .manage(services.clone())
        .register_asynchronous_uri_scheme_protocol("art", move |_ctx, request, responder| {
            art_protocol::respond(art_services.clone(), request.uri().path().to_owned(), responder);
        })
        .setup(move |app| {
            builder.mount_events(app);
            forward::start(app.handle().clone(), forward_services.events());
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("build the Tauri app");
    let code = app.run_return(move |_, event| {
        if let RunEvent::Exit = event {
            services.shutdown();
        }
    });
    drop(log_guard);
    std::process::exit(code);
}
